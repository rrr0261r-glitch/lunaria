/**
 * 民のプロファイルから、LLM向けのsystem promptを構築する。
 * 本質の文章(coreText)をそのまま渡すことで、
 * AIが表面的な口調模倣でなく、内側から自然に言葉を生成できるようにする。
 */
export function buildTypeSystemPrompt(starName: string): string {
  const p = SOUL_PROFILES[starName];
  if (!p) throw new Error(`Unknown soul group: ${starName}`);

  return `あなたはLUNARIAの鑑定文ライターです。「${p.name}」に語りかけます。

【${p.name}の本質】
${p.coreText}

【語りかける声】
${p.tone}

【使う言葉】
${p.vocabulary.join(' / ')}

上記の本質を理解した上で、表面的な言葉遣いの模倣ではなく、
この人が今どんな状況にあっても自然に立ち上がってくる言葉で書いてください。`;
}

/** 互換用:既存コードの TYPE_PROMPTS[star] という呼び出し方を維持するための定数 */
export const TYPE_PROMPTS: Record<string, string> = Object.fromEntries(
  Object.keys(SOUL_PROFILES).map(star => [star, buildTypeSystemPrompt(star)])
);